/** Lightweight i18n — English / Japanese bilingual support */

export type Lang = 'en' | 'ja';

const STORAGE_KEY = 'gansu-lang';

let currentLang: Lang = 'en';

/** Load saved language preference (call early). */
export function initLang(): void {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === 'ja' || saved === 'en') currentLang = saved;
}

/** Get current language. */
export function getLang(): Lang {
  return currentLang;
}

/** Toggle EN↔JA. Returns the new language. */
export function toggleLang(): Lang {
  currentLang = currentLang === 'en' ? 'ja' : 'en';
  localStorage.setItem(STORAGE_KEY, currentLang);
  // Notify global listeners (e.g. nav.ts footer auto-updates)
  if (typeof document !== 'undefined') {
    document.dispatchEvent(new CustomEvent('gansu-lang-change', { detail: currentLang }));
  }
  return currentLang;
}

/** Translate a key to the current language string. */
export function t(key: string): string {
  const dict = translations[currentLang];
  return dict[key] ?? translations.en[key] ?? key;
}

